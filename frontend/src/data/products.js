/**
 * Format currency in Indian Rupees (INR)
 * e.g., 174999 -> ₹1,74,999
 */
export function formatINR(amount) {
  if (typeof amount !== 'number') amount = Number(amount) || 0;
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}
